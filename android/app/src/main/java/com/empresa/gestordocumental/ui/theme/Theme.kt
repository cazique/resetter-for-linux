/** Colores semánticos extra que Material 3 no cubre (estados de documento). */
@Immutable
data class ExtendedColors(
    val statusPending: Color,
    val statusProcessed: Color,
    val statusArchived: Color,
)

private val LightExtendedColors = ExtendedColors(
    statusPending = StatusColors.PendingLight,
    statusProcessed = StatusColors.ProcessedLight,
    statusArchived = StatusColors.ArchivedLight,
)

private val DarkExtendedColors = ExtendedColors(
    statusPending = StatusColors.PendingDark,
    statusProcessed = StatusColors.ProcessedDark,
    statusArchived = StatusColors.ArchivedDark,
)

val LocalExtendedColors = staticCompositionLocalOf { LightExtendedColors }

/**
 * Tema de la aplicación con soporte nativo de modo claro/oscuro.
 *
 * @param darkTheme por defecto sigue la configuración del sistema.
 * @param dynamicColor usa Material You (Android 12+). Desactivado por defecto
 *        para mantener la identidad corporativa.
 */
@Composable
fun GestorTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColors
        else -> LightColors
    }
    val extendedColors = if (darkTheme) DarkExtendedColors else LightExtendedColors

    // Iconos de barras de sistema legibles según el modo (edge-to-edge).
    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as? Activity)?.window ?: return@SideEffect
            val insetsController = WindowCompat.getInsetsController(window, view)
            insetsController.isAppearanceLightStatusBars = !darkTheme
            insetsController.isAppearanceLightNavigationBars = !darkTheme
        }
    }

    CompositionLocalProvider(LocalExtendedColors provides extendedColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = AppTypography,
            content = content,
        )
    }
}

/** Acceso cómodo: `MaterialTheme.extendedColors.statusPending`. */
val MaterialTheme.extendedColors: ExtendedColors
    @Composable get() = LocalExtendedColors.current
